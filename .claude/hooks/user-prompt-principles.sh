#!/usr/bin/env bash
# UserPromptSubmit 钩子 —— 每一轮、在我动手之前，把四条第一性原理变成**四个必答问题**注入上下文。
#
# ⚠ 为什么不是「去读 docs/PRINCIPLES-work-mechanism.md」：
# 2026-09-18 实测 —— CLAUDE.md 整份（约 1000 行）**每一轮都已经在上下文里**，
# 当天同族错误仍犯 3 次、自匹杀进程仍犯 2 次。**规则在眼前 ≠ 会照做。**
# 长度本身就是失效原因：能被处理的是**四个问题**，不是一千行条款。
#
# 所以这里只注入问题，不注入条款。原文在 docs/PRINCIPLES-work-mechanism.md。
set -uo pipefail

cat <<'EOF'
────────── 开口之前，先答这四问（docs/PRINCIPLES-work-mechanism.md） ──────────

P1 证据 · 我手上这个证据，和我要断言的那个对象，是**同一个东西**吗？
   （grep 到的串 ≠ 那个赋值存在 · 台账说没做 ≠ 真没做 · 桥的绿 ≠ 沙盘的绿）
   ⚠ 报「0 处 / 不存在 / 没有消费方」之前，必须先用同一支查法查一个**确知存在**的东西。

P2 缺口 · 我这个修法，会不会让缺口**看起来**没了？
   （算不出来填 0 / 填 hash / 填默认值 —— 以及「把教训写下来」同样是一种填补）
   ⚠ 指标必须有期望值：`0/7295` 是装饰，`0/7295（期望 7295）` 才是欠条。

P3 规模 · 同类共有几个？（先数分母，再修实例）
   ⚠ 修完必问：**下一个同类出现时，什么东西会先说话？**
     答不出「是机器」= 没修完。

P4 位置 · 这个结论，有没有一个**不知道我答案**的人量过？
   （当天纠正来源：中立测量员 5/5 · dev 顶回来 3/3 · 仓主 4/4 · 我自己读规则想起来 **0**）

────────── 动手之前，还有两条是硬的 ──────────
· 「看」和「动」分成两次工具调用 —— 同一条命令里既取证据又执行不可逆动作，
  证据来不及拦住动作（当天真实损失：杀掉了一个还活着的 agent 的服务）。
· 做完的先并，再派新的 —— 验证完 ≠ 交付。
EOF
exit 0

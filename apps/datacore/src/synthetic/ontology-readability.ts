/**
 * WO-63-SCHEMA-READABILITY · 出厂本体口径目录（"业务专家 1 小时读懂 80%"的数据面）。
 *
 * **本文件是数据不是机制**：承载可读性的字段（PropertyDef.description/unit/displayName、
 * ObjectTypeDef.businessDefinition）本就在本体里，只是**空的**——本目录把它们填满，经
 * `applyReadability()` 在出厂本体装配时注入，前端/Agent 经既有 type-semantics 投影消费。
 *
 * 三条纪律（违反即门红）：
 *  ① **单位只填有量纲的**：比率/系数/序号/计数/评分/经纬度标 `dimensionless`；量纲随行承载的
 *     （如 Metric.target 随 Metric.unit）标 `per-row`。给比率硬凑一个"个"比留空更坏。
 *  ② **不改 propKey**：中文名走 displayName（改 key 会断掉全平台引用），前端渲染 `displayName ?? propKey`。
 *  ③ **口径写真值不写套话**：同名字段在不同类型量纲可能不同（`Base.util` 是 0–100 百分数，
 *     `Line.utilization` 是 0–1 小数），description 必须把这种坑写明——这正是"读得懂"的本体价值。
 */

/** 属性口径条目（description 必填；unit 与 unitExempt 二选一，数值属性必须二者有其一）。 */
export interface PropReadability {
  displayName: string;
  description: string;
  unit?: string;
  unitExempt?: "dimensionless" | "per-row";
}

/** 有量纲属性：`d(中文名, 口径, 单位)`；非数值属性省略单位。 */
const d = (displayName: string, description: string, unit?: string): PropReadability =>
  unit ? { displayName, description, unit } : { displayName, description };

/** 天然无量纲的数值属性（比率/系数/序号/计数/评分/经纬度）：诚实不填单位。 */
const n = (displayName: string, description: string): PropReadability => ({
  displayName,
  description,
  unitExempt: "dimensionless",
});

/** 量纲逐行承载的数值属性（同对象另有 unit 字段给出该行量纲）。 */
const pr = (displayName: string, description: string): PropReadability => ({
  displayName,
  description,
  unitExempt: "per-row",
});


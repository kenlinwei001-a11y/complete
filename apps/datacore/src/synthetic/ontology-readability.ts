// ---------------------------------------------------------------------------
// 注入器：出厂本体装配时把口径目录合并进 PropertyDef / ObjectTypeDef
// ---------------------------------------------------------------------------

type FactoryType = Omit<ObjectTypeDef, "id" | "tenantId" | "version" | "status">;

/**
 * 把本目录的口径注入某类型的属性（**加性合并**：目录未覆盖的属性原样保留，
 * 已有 unit 由目录覆盖——目录是量纲的单一来源，见 `Order.qty` 件→套 的口径纠正）。
 */
export function applyPropReadability(typeKey: string, props: PropertyDef[]): PropertyDef[] {
  const cat = PROP_READABILITY[typeKey];
  if (!cat) return props;
  return props.map((p) => {
    const e = cat[p.propKey];
    if (!e) return p;
    const out: PropertyDef = { ...p, displayName: e.displayName, description: e.description };
    if (e.unit) {
      out.unit = e.unit;
      delete out.unitExempt;
    } else if (e.unitExempt) {
      out.unitExempt = e.unitExempt;
      delete out.unit;
    }
    return out;
  });
}

/** 把口径目录 + 业务定义注入整批出厂类型（合成建域装配的收口点）。 */
export function applyReadability<T extends FactoryType>(types: T[]): T[] {
  return types.map((t) => {
    const bd = TYPE_BUSINESS_DEFINITIONS[t.key];
    return {
      ...t,
      properties: applyPropReadability(t.key, t.properties),
      ...(bd ? { businessDefinition: bd } : {}),
    };
  });
}

/** 目录中用到的全部单位（治理单位字典须覆盖它，否则管理页改同一类型会被字典拒绝）。 */
export function catalogUnits(): string[] {
  const s = new Set<string>();
  for (const props of Object.values(PROP_READABILITY)) {
    for (const e of Object.values(props)) if (e.unit) s.add(e.unit);
  }
  return [...s].sort();
}
